import test from 'node:test';
import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';

test('dois mil itens ficam em dois cards e tabela paginada permite localizar e filtrar', async () => {
 const dom = new JSDOM('<div id="cards"></div>', { url: 'https://validasuper.test' });
 globalThis.window = dom.window; globalThis.document = dom.window.document;
 window.supabase = { createClient: () => ({}) };
 window.HTMLDialogElement.prototype.showModal = function () { this.setAttribute('open', ''); };
 window.HTMLDialogElement.prototype.close = function () { this.dispatchEvent(new window.Event('close')); };
 const { renderItens } = await import('../js/lifecycleUI.js');
 const items = Array.from({ length: 2000 }, (_, n) => ({ id: String(n), origem_codigo: n < 1000 ? 'LOTE-A' : 'LOTE-B', produto_nome: `Café ${String(n).padStart(4,'0')}`, produtos: { ean: `789${n}` }, lote_fisico: `FAB-${n}`, localizacao: n % 2 ? 'Depósito' : 'Gôndola', tipo: 'VAL', status: 'ativo', quantidade: 10, preco_atual: 2, data_vencimento: '2027-01-01', faixa: '60+', pendencias: n % 2 ? ['Conferir'] : [], eventos: [] }));
 const container = document.querySelector('#cards');
 renderItens(items, container, { funcao: 'operador' }, async () => ({ itens: items }));
 assert.equal(container.querySelectorAll('article').length, 2);
 assert.equal(document.querySelector('table'), null);
 container.querySelector('.vs-lot-open').click();
 const modal = document.querySelector('.vs-lot-dialog');
 const rows = () => [...modal.querySelectorAll('tbody tr[data-item-id]')];
 assert.equal(rows().length, 25); assert.equal(rows()[0].dataset.itemId, '0');
 modal.querySelector('.vs-pagination button:last-child').click();
 assert.equal(rows()[0].dataset.itemId, '25');
 const search = modal.querySelector('[type=search]');
 search.value = 'cafe 0999'; search.dispatchEvent(new window.Event('input'));
 assert.equal(rows().length, 1); assert.equal(rows()[0].dataset.itemId, '999');
 search.value = '789123'; search.dispatchEvent(new window.Event('input'));
 assert.equal(rows()[0].dataset.itemId, '123');
 search.value = 'FAB-456'; search.dispatchEvent(new window.Event('input'));
 assert.equal(rows()[0].dataset.itemId, '456');
 search.value = ''; search.dispatchEvent(new window.Event('input'));
 const pending = modal.querySelector('[type=checkbox]'); pending.checked = true; pending.dispatchEvent(new window.Event('change'));
 assert.match(modal.querySelector('[role=status]').textContent, /de 500 itens/);
 const local = modal.querySelector('[aria-label="Filtrar localização"]'); local.value = 'Gôndola'; local.dispatchEvent(new window.Event('change'));
 assert.equal(rows().length, 0); assert.match(modal.textContent, /Nenhum item corresponde/);
 pending.checked = false; pending.dispatchEvent(new window.Event('change'));
 const size = modal.querySelector('[aria-label="Itens por página"]'); size.value = '100'; size.dispatchEvent(new window.Event('change'));
 assert.equal(rows().length, 100);
 assert.equal(modal.querySelector('[aria-label="Corrigir quantidade"]'), null);
 modal.close();
 renderItens(items.map(i => ({ ...i, lote_vencidos: 'VENC-DIA' })), container, { funcao: 'operador' }, async () => {}, { groupBy: 'vencidos' });
 assert.equal(container.querySelectorAll('article').length, 1);
 renderItens(items.slice(0, 26).map((i, n) => ({ ...i, origem_codigo: `LOTE-${String(n).padStart(2, '0')}` })), container, { funcao: 'operador' }, async () => {});
 assert.equal(container.querySelectorAll('article').length, 12);
 container.querySelector('.vs-pagination button:last-child').click();
 assert.match(container.querySelector('h3').textContent, /LOTE-12/);
 const lotSearch = container.querySelector('[type=search]'); lotSearch.value = 'LOTE-25'; lotSearch.dispatchEvent(new window.Event('input'));
 assert.equal(container.querySelectorAll('article').length, 1);
 assert.equal(container.querySelector('h3').textContent, 'LOTE-25');
 dom.window.close();
});

test('salvar correção atualiza a tabela aberta e conserva busca e auditoria', async () => {
 const dom = new JSDOM('<div id="cards"></div>', { url: 'https://validasuper.test' });
 globalThis.window = dom.window; globalThis.document = dom.window.document;
 window.supabase = { createClient: () => ({}) };
 window.HTMLDialogElement.prototype.showModal = function () { this.setAttribute('open', ''); };
 window.HTMLDialogElement.prototype.close = function () { this.dispatchEvent(new window.Event('close')); };
 const { renderItens } = await import('../js/lifecycleUI.js');
 const { lifecycleService } = await import('../js/lifecycleService.js');
 const item = { id: '1', origem_codigo: 'LOTE', produto_nome: 'Café', tipo: 'VAL', status: 'ativo', quantidade: 10, faixa: '60+', pendencias: [], eventos: [] };
 const refreshed = { ...item, quantidade: 12, eventos: [{ tipo: 'Correção', saldo_anterior: 10, saldo_novo: 12, usuario_nome: 'Maria', ocorrido_em: '2026-10-14T12:00:00Z', motivo: 'Conferência física' }] };
 const container = document.querySelector('#cards');
 const refresh = async () => { renderItens([refreshed], container, { funcao: 'administrador' }, refresh); return { itens: [refreshed] }; };
 renderItens([item], container, { funcao: 'administrador' }, refresh);
 container.querySelector('.vs-lot-open').click();
 const modal = document.querySelector('.vs-lot-dialog');
 const search = modal.querySelector('[type=search]'); search.value = 'cafe'; search.dispatchEvent(new window.Event('input'));
 modal.querySelector('[aria-label="Corrigir quantidade"]').click();
 const form = document.querySelector('dialog form');
 form.querySelector('[type=number]').value = 12; form.querySelector('[type=checkbox]').checked = true;
 form.querySelectorAll('[type=text]')[1].value = 'Conferência física';
 const original = lifecycleService.registrar;
 lifecycleService.registrar = async () => {};
 try {
  await form.onsubmit(new window.Event('submit', { cancelable: true }));
  assert.ok(modal.isConnected); assert.equal(search.value, 'cafe');
  assert.equal(modal.querySelector('tbody .vs-number').textContent, '12');
  assert.match(modal.querySelector('.vs-row-audit').textContent, /Maria/);
  assert.match(container.textContent, /quantidade corrigida/);
 } finally { lifecycleService.registrar = original; dom.window.close(); }
});
